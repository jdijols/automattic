// T4-U1 — the §3.6 experiment REPORT WRITER. Formats an ExperimentReport (the
// machine result from run.ts) into the human-readable markdown a reviewer signs
// off on in issue #23 (the C-single-vs-C-decomposed HITL lock). It is a PURE
// function — no clock, no randomness, no I/O — so the mock-driven test under
// tests/ can assert its output byte-stably and the live runner (run.live.test.ts)
// can write the same bytes to RESULTS.md.
//
// SECURITY: the writer surfaces ONLY the §5.2 error CODES already carried on the
// report (run.ts records nothing else from a failed run); it never reaches for a
// raw provider cause, so a credential cannot enter RESULTS.md through this path.
import { type ArmMetrics, type ExperimentReport } from "./run";

/** Render a fraction in [0,1] as a one-decimal percentage (0.5 → "50.0%"). */
function pct(fraction: number): string {
  return `${(fraction * 100).toFixed(1)}%`;
}

/** Render a millisecond latency. Zero (no successful run) renders as "n/a". */
function ms(value: number, hadSamples: boolean): string {
  return hadSamples ? `${Math.round(value)} ms` : "n/a";
}

/** Aggregate the flat §5.2 failure-code list into "CODE×N, CODE×M" (sorted). */
function failureCodeSummary(codes: readonly string[]): string {
  if (codes.length === 0) return "—";
  const counts = new Map<string, number>();
  for (const code of codes) counts.set(code, (counts.get(code) ?? 0) + 1);
  return [...counts.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([code, n]) => `${code}×${n}`)
    .join(", ");
}

/** The per-arm metrics table row. */
function armRow(name: string, m: ArmMetrics): string {
  const hadSuccess = m.firstTrySuccessRate > 0;
  const cells = [
    name,
    `${pct(m.firstTrySuccessRate)} (${Math.round(m.firstTrySuccessRate * m.runs)}/${m.runs})`,
    ms(m.successLatencyP50Ms, hadSuccess),
    ms(m.successLatencyP95Ms, hadSuccess),
    `${m.diversity.distinctPatterns} patterns / ${m.diversity.distinctCompositions} compositions (n=${m.diversity.sampleSize})`,
    m.regionDepths.length > 0 ? String(Math.max(...m.regionDepths)) : "n/a",
    m.withinBudget ? "yes" : "no",
    failureCodeSummary(m.failureCodes),
  ];
  return `| ${cells.join(" | ")} |`;
}

/**
 * Format an ExperimentReport as markdown for RESULTS.md. The output carries four
 * sections — Scope, Per-arm metrics, Recommendation — each with stable headings the
 * mock test asserts. The recommendation decision/rationale are rendered verbatim so
 * the human's decision in issue #23 reads exactly what the harness computed.
 */
export function formatExperimentReport(report: ExperimentReport): string {
  const { scope, perArm, recommendation } = report;

  const lines: string[] = [];
  lines.push("# §3.6 First-Try-Success Experiment — Results");
  lines.push("");
  lines.push(
    "> Generated by `npm run experiment` (`experiments/first-try-success/run.live.test.ts`). " +
      "This is a RECOMMENDATION, not a lock — the C-single-vs-C-decomposed arm decision is the " +
      "human-in-the-loop sign-off in issue #23.",
  );
  lines.push("");

  lines.push("## Scope");
  lines.push("");
  lines.push(`- **Arms measured:** ${scope.arms.join(", ")}`);
  lines.push(`- **Arms excluded (logged, not silently cut):** ${scope.excludedArms.join("; ")}`);
  lines.push(`- **Corpus:** ${scope.archetypes} archetypes × k=${scope.k} paraphrases each`);
  lines.push(`- **Judged by:** ${scope.layers}`);
  lines.push(`- **Tuning mode:** ${scope.tuning}`);
  lines.push("");

  lines.push("## Per-arm metrics");
  lines.push("");
  lines.push(
    "| Arm | First-try success | Latency p50 | Latency p95 | Diversity (distinct patterns / compositions) | Max region depth | Within budget | Failure codes |",
  );
  lines.push("| --- | --- | --- | --- | --- | --- | --- | --- |");
  for (const [name, metrics] of Object.entries(perArm)) {
    lines.push(armRow(name, metrics));
  }
  lines.push("");
  lines.push(
    "_Failed-run latencies are tracked separately from the success p50/p95 (origin §3.6) and are not folded into the percentiles above._",
  );
  lines.push("");

  lines.push("## Recommendation");
  lines.push("");
  lines.push(`- **Decision:** ${recommendation.decision}`);
  lines.push(`- **Rationale:** ${recommendation.rationale}`);
  lines.push("");

  return lines.join("\n");
}
